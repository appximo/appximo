func buildOAComponents(s *schema.APISchema) map[string]any {
	schemas := map[string]any{
		"ErrorResponse": map[string]any{
			"type":     "object",
			"required": []string{"error"},
			"properties": map[string]any{
				"error": map[string]any{"type": "string"},
			},
		},
		// The declarative-validation 422 body: every failing field reported at once.
		// Matches builder.go writeValidationErrs: {"error":"validation_failed","fields":[{field,rule,message}]}.
		"ValidationError": map[string]any{
			"type":     "object",
			"required": []string{"field", "rule", "message"},
			"properties": map[string]any{
				"field":   map[string]any{"type": "string"},
				"rule":    map[string]any{"type": "string"},
				"message": map[string]any{"type": "string"},
			},
		},
		"ValidationErrorResponse": map[string]any{
			"type":     "object",
			"required": []string{"error", "fields"},
			"properties": map[string]any{
				"error":  map[string]any{"type": "string", "example": "validation_failed"},
				"fields": map[string]any{"type": "array", "items": oaSchemaRef("ValidationError")},
			},
		},
		// ENG-40: the aggregate endpoint's response. Without group_by, ONE
		// object carrying only the requested keys; with group_by, {"groups":
		// [...]} where each group carries its group-by field values plus the
		// same aggregate keys. sum/avg values are numbers; min/max values are
		// numbers or timestamps depending on the field's type.
		"AggregateResponse": map[string]any{
			"type":        "object",
			"description": "Without group_by: one object with only the requested keys (count, sum, avg, min, max). With group_by: {\"groups\": [...]} — each group carries its group-by field values plus the requested aggregate keys.",
			"properties": map[string]any{
				"count": map[string]any{"type": "integer"},
				"sum":   map[string]any{"type": "object", "additionalProperties": map[string]any{"type": "number"}},
				"avg":   map[string]any{"type": "object", "additionalProperties": map[string]any{"type": "number"}},
				"min":   map[string]any{"type": "object", "additionalProperties": map[string]any{}},
				"max":   map[string]any{"type": "object", "additionalProperties": map[string]any{}},
				"groups": map[string]any{
					"type":  "array",
					"items": map[string]any{"type": "object", "additionalProperties": true},
				},
			},
		},
		// Matches the actual list response meta. page/has_prev are ABSENT on a
		// cursor (?after/?before) request — keyset pagination has no page number,
		// and meta must not invent one (ENG-15). total/total_pages appear only
		// when the caller opted in with ?count=true (ENG-23); no `links` object —
		// the live engine emits meta only (keyset pages via ?after=<last id>).
		"PaginationMeta": map[string]any{
			"type":     "object",
			"required": []string{"per_page", "has_next"},
			"properties": map[string]any{
				"page":        map[string]any{"type": "integer", "description": "absent on a cursor (?after/?before) request — a cursor request has no page number"},
				"per_page":    map[string]any{"type": "integer"},
				"has_next":    map[string]any{"type": "boolean", "description": "more rows exist after this page (continue with ?after=<last item's id>)"},
				"has_prev":    map[string]any{"type": "boolean", "description": "absent on a cursor request"},
				"total":       map[string]any{"type": "integer", "description": "present only with ?count=true — the COUNT(*) over the same filtered, RBAC-scoped set"},
				"total_pages": map[string]any{"type": "integer", "description": "present only with ?count=true"},
			},
		},
	}
	addOAAuthSchemas(schemas)

	for _, name := range sortedResourceKeys(s) {
		res := s.Resources[name]
		title := toPascalCase(name)
		schemas[title] = oaResourceSchema(&res, true)
		schemas[title+"Input"] = oaResourceSchema(&res, false)
		// PatchInput mirrors Input but with every field optional (no required list),
		// matching PATCH semantics (only supplied fields are updated).
		patchInput := oaResourceSchema(&res, false)
		delete(patchInput, "required")
		schemas[title+"PatchInput"] = patchInput
		schemas[title+"ListResponse"] = map[string]any{
			"type": "object",
			"properties": map[string]any{
				"data": map[string]any{
					"type":  "array",
					"items": oaSchemaRef(title),
				},
				"meta": oaSchemaRef("PaginationMeta"),
			},
		}
	}

	return map[string]any{
		"securitySchemes": map[string]any{
			"bearerAuth": map[string]any{
				"type":         "http",
				"scheme":       "bearer",
				"bearerFormat": "JWT",
			},
		},
		"schemas": schemas,
		"responses": map[string]any{
			"Error400": oaErrResp("Bad request — invalid input, UUID format, or query parameter"),
			"Error401": oaErrResp("Authentication required — include a valid Bearer token"),
			"Error403": oaErrResp("Insufficient permissions for this action"),
			"Error404": oaErrResp("Resource not found"),
			"Error409": oaErrResp("Conflict — a unique constraint would be violated"),
			"Error413": oaErrResp("Request body too large (1 MiB limit)"),
			"Error429": oaErrResp("Too many requests — rate or login-attempt limit exceeded (see Retry-After)"),
			"Error422": map[string]any{
				"description": "Validation failed (every offending field is listed), or a before_create/before_update hook rejected the request",
				"content":     oaJSONContent(oaSchemaRef("ValidationErrorResponse")),
			},
		},
	}
}

