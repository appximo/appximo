func oaReqBody(schemaName string) map[string]any {
	return map[string]any{"required": true, "content": oaJSONContent(oaSchemaRef(schemaName))}
}

func oaReqBodyOptional(schemaName string) map[string]any {
	return map[string]any{"required": false, "content": oaJSONContent(oaSchemaRef(schemaName))}
}

func oaListOp(name, title string, res *schema.ResourceSchema) map[string]any {
	params := []any{
		oaQueryParam("page", map[string]any{
			"type":    "integer",
			"default": 1,
			"minimum": 1,
		}),
		oaQueryParam("per_page", map[string]any{
			"type":    "integer",
			"default": 20,
			"minimum": 1,
			"maximum": 100,
		}),
		oaQueryParamDesc("sort", map[string]any{"type": "string", "enum": oaSortEnum(res)},
			"Field to sort by (legacy). Prefer order[field]=asc|desc"),
		oaQueryParamDesc("order", map[string]any{"type": "string", "enum": []string{"asc", "desc"}, "default": "asc"},
			"Sort direction for the sort field (legacy)"),
		oaQueryParamDesc("search", map[string]any{"type": "string"},
			"Full-text search across all string fields (ILIKE)"),
	}

	// order[field] params
	for _, fname := range sortedFieldKeys(res) {
		params = append(params, oaQueryParamDesc(
			"order["+fname+"]",
			map[string]any{"type": "string", "enum": []string{"asc", "desc"}},
			"Sort by "+fname,
		))
	}

	// filter params with operator variants per field type
	for _, fname := range sortedFieldKeys(res) {
		fd := res.Fields[fname]
		baseSchema := oaFieldType(fd)
		params = append(params, oaQueryParamDesc(
			"filter["+fname+"]",
			baseSchema,
			oaFilterDesc(fname, fd.Type),
		))
		// add operator variants for applicable types
		for _, op := range oaOpsForType(fd.Type) {
			if op == "eq" {
				continue // already covered by filter[field]
			}
			params = append(params, oaQueryParamDesc(
				"filter["+fname+"]["+op+"]",
				baseSchema,
				oaOpDesc(fname, op),
			))
		}
	}

	return map[string]any{
		"operationId": "list" + title,
		"summary":     "List " + name,
		"tags":        []string{name},
		"parameters":  params,
		"responses": map[string]any{
			"200": oaSuccessResp(oaSchemaRef(title + "ListResponse")),
			"400": oaRespRef("Error400"),
			"401": oaRespRef("Error401"),
			"403": oaRespRef("Error403"),
		},
	}
}

