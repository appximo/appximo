type openAPISpec struct {
	OpenAPI    string           `yaml:"openapi" json:"openapi"`
	Info       map[string]any   `yaml:"info" json:"info"`
	Servers    []map[string]any `yaml:"servers,omitempty" json:"servers,omitempty"`
	Security   []map[string]any `yaml:"security" json:"security"`
	Paths      map[string]any   `yaml:"paths" json:"paths"`
	Components map[string]any   `yaml:"components" json:"components"`
}

// buildOASpec assembles the full OpenAPI 3.0.3 document object for an APISchema
// plus the app's registered custom routes (nil for a pure `serve` binary — the
// document is then byte-identical to before ENG-33). It is the single source of
// truth shared by the YAML and JSON marshallers, so the `appitools openapi` CLI
// and the served /openapi.json are byte-for-byte the same contract in two
// encodings.
func buildOASpec(s *schema.APISchema, baseURL string, routes []CustomRoute) openAPISpec {
	if baseURL == "" {
		baseURL = "/"
	}
	paths := buildOAPaths(s)
	addOACustomPaths(paths, routes)
	return openAPISpec{
		OpenAPI: "3.0.3",
		Info: map[string]any{
			"title":   s.Name,
			"version": s.Version,
			"description": "Generated by Appitools — https://github.com/miguelangel/appitools. " +
				"Building a client or frontend with an AI agent? The engine prints its full agent-facing contract: " +
				"`appitools spec` (the schema grammar), `appitools backend-spec` (custom handlers/hooks/jobs), " +
				"`appitools frontend-spec` (the API contract a UI consumes, error→screen-state mapping, files).",
		},
		Servers:    []map[string]any{{"url": baseURL, "description": "API server"}},
		Security:   []map[string]any{{"bearerAuth": []string{}}},
		Paths:      paths,
		Components: buildOAComponents(s),
	}
}

// GenerateOpenAPI produces an OpenAPI 3.0.3 YAML document from an APISchema.
// baseURL is set as the server URL (defaults to "/" when empty).
func GenerateOpenAPI(s *schema.APISchema, baseURL string) ([]byte, error) {
	return GenerateOpenAPIWithRoutes(s, baseURL, nil)
}

// GenerateOpenAPIJSON produces the SAME OpenAPI 3.0.3 document as GenerateOpenAPI
// but JSON-encoded — the format Swagger UI and most client generators consume. The
// engine serves it at GET /openapi.json.
func GenerateOpenAPIJSON(s *schema.APISchema, baseURL string) ([]byte, error) {
	return GenerateOpenAPIJSONWithRoutes(s, baseURL, nil)
}

// GenerateOpenAPIWithRoutes is GenerateOpenAPI plus the app's registered custom
// routes as path items (ENG-33) — what a framework-mode App serves, so the
// contract covers the WHOLE surface, not only the generated half.
func GenerateOpenAPIWithRoutes(s *schema.APISchema, baseURL string, routes []CustomRoute) ([]byte, error) {
	return yaml.Marshal(buildOASpec(s, baseURL, routes))
}

// GenerateOpenAPIJSONWithRoutes is the JSON encoding of GenerateOpenAPIWithRoutes.
func GenerateOpenAPIJSONWithRoutes(s *schema.APISchema, baseURL string, routes []CustomRoute) ([]byte, error) {
	return json.MarshalIndent(buildOASpec(s, baseURL, routes), "", "  ")
}

// ── paths ─────────────────────────────────────────────────────────────────────

func buildOAPaths(s *schema.APISchema) map[string]any {
	paths := map[string]any{}
	// Auth-as-product endpoints (AUTH-CORE-V1 …): always part of the engine's API
	// surface, independent of the schema, so they are always documented.
	addOAAuthPaths(paths)
	// File store routes exist whenever no schema resource is literally named "files".
	if _, taken := s.Resources["files"]; !taken {
		addOAFilePaths(paths)
	}
	for _, name := range sortedResourceKeys(s) {
		res := s.Resources[name]
		title := toPascalCase(name)
		paths["/api/"+name] = map[string]any{
			"get":  oaListOp(name, title, &res),
			"post": oaCreateOp(name, title),
		}
		paths["/api/"+name+"/{id}"] = map[string]any{
			"get":    oaGetOp(name, title),
			"put":    oaReplaceOp(name, title),
			"patch":  oaUpdateOp(name, title),
			"delete": oaDeleteOp(name, title),
		}
		// subresource paths
		for _, fname := range sortedFieldKeys(&res) {
			fd := res.Fields[fname]
			if fd.Relation == "" {
				continue
			}
			relName := strings.TrimSuffix(fname, "_id")
			relTitle := toPascalCase(fd.Relation)
			paths["/api/"+name+"/{id}/"+relName] = map[string]any{
				"get": oaSubresourceOp(name, title, relName, relTitle, fd.Relation, fname),
			}
		}
	}
	return paths
}

