func oaResourceSchema(res *schema.ResourceSchema, includeAuto bool) map[string]any {
	props := map[string]any{}
	if includeAuto {
		props["id"] = map[string]any{"type": "string", "format": "uuid", "readOnly": true}
	}
	var required []string

	for _, fname := range sortedFieldKeys(res) {
		fd := res.Fields[fname]
		if fd.Auto.Enabled() && !includeAuto {
			continue
		}
		props[fname] = oaPropertySchema(fname, fd)
		if fd.Required && !fd.Auto.Enabled() {
			required = append(required, fname)
		}
	}

	out := map[string]any{
		"type":       "object",
		"properties": props,
	}
	if len(required) > 0 {
		sort.Strings(required)
		out["required"] = required
	}
	// Import declaration (WRITE-ASYMMETRY-S1): the resource accepts these
	// governed fields on CREATE from import-granted roles — published so a
	// generic tool can discover the capability from the contract instead of
	// probing. The granted ROLE LIST is deliberately not published: the spec
	// is unauthenticated and role names are not (the ENG-27 anti-enumeration
	// asymmetry). The governed properties keep readOnly:true — that is the
	// truth for every caller outside the grant.
	if res.Import != nil {
		out["x-appximo-import"] = map[string]any{"fields": res.ImportDeclaredFields()}
	}
	return out
}

// oaPropertySchema is oaFieldType plus the x-appximo-* vendor extensions a
// GENERIC tool needs to drive a UI/client from the contract alone
// (FIELD-FEEDBACK-S1, FE5 + PATRON-BACKOFFICE §6). It is used for COMPONENT
// property schemas only — filter query parameters keep the plain oaFieldType,
// where these keys would be noise. The extensions:
//
//   - x-appximo-relation:   the FK's target resource (fd.Relation)
//   - x-appximo-references: the FK's target COLUMN — "id" unless the schema
//     declared otherwise. THE blind spot of FE5: the $user_id pattern the
//     framework itself recommends requires FKs referencing user_id, and a
//     generic relation selector that always sends the row's id violates
//     exactly those FKs; before this key every tool needed a hand-written
//     exception map.
//   - x-appximo-file (+ x-appximo-accept / x-appximo-max-bytes): a file field
//     was indistinguishable from any other uuid FK; the marks let a tool
//     generate the upload→attach widget with the declared policy.
//   - x-appximo-initial / x-appximo-transitions: the state machine, so a UI
//     offers only legal moves (a terminal state is present with an empty
//     list). frontend-spec used to say these were "not in the OpenAPI" —
//     they are now.
func oaPropertySchema(fname string, fd schema.FieldDef) map[string]any {
	m := oaFieldType(fd)
	// Engine-managed timestamps (SILENT-CORRUPTION-S1): the standard readOnly
	// keyword (they appear in responses, never in request bodies — before this
	// only `id` carried it) plus x-appximo-auto naming the EFFECTIVE role —
	// "update" when the engine refreshes the column on every update, "create"
	// when it is set once at insert. A generic tool (the /app back-office, a
	// form generator) reads the truth from the contract instead of guessing it
	// from the two English field names.
	if fd.Auto.Enabled() {
		m["readOnly"] = true
		m["x-appximo-auto"] = fd.EffectiveAutoRole(fname)
	}
	// The declared create-default, as the STANDARD OpenAPI keyword (ENG-38).
	// It tells a generic tool (the /app back-office, a form generator) that a
	// `required` field with a default is satisfiable by OMISSION — without it,
	// every such tool over-demands a value the engine would have filled.
	if fd.Default != nil {
		m["default"] = fd.Default
	}
	if fd.Relation != "" {
		m["x-appximo-relation"] = fd.Relation
		ref := fd.References
		if ref == "" {
			ref = "id" // the schema-level default, made explicit for tools
		}
		m["x-appximo-references"] = ref
	}
	if fd.Type == "file" {
		m["x-appximo-file"] = true
		if len(fd.Accept) > 0 {
			m["x-appximo-accept"] = []string(fd.Accept)
		}
		if fd.MaxBytes > 0 {
			m["x-appximo-max-bytes"] = fd.MaxBytes
		}
	}
	if sm := fd.StateMachine; sm != nil {
		known := sm.KnownStates()
		states := make([]string, 0, len(known))
		for st := range known {
			states = append(states, st)
		}
		sort.Strings(states)
		trans := make(map[string][]string, len(states))
		for _, st := range states {
			if outs := sm.Transitions[st]; len(outs) > 0 {
				trans[st] = outs
			} else {
				trans[st] = []string{} // terminal: present, no exits
			}
		}
		m["x-appximo-initial"] = []string(sm.Initial)
		m["x-appximo-transitions"] = trans
	}
	return m
}

// oaFieldType maps a FieldDef to an OpenAPI type schema object, including the
// declarative validation rules (S44): pattern, min/maxLength, minimum/maximum
// and format translate to their exact OpenAPI equivalents.
func oaFieldType(fd schema.FieldDef) map[string]any {
	switch fd.Type {
	case "string", "text":
		m := map[string]any{"type": "string"}
		if len(fd.Enum) > 0 {
			m["enum"] = fd.Enum
		}
		if fd.MinLength != nil {
			m["minLength"] = *fd.MinLength
		}
		if fd.MaxLength != nil {
			m["maxLength"] = *fd.MaxLength
		}
		if fd.Pattern != "" {
			m["pattern"] = fd.Pattern
		}
		switch fd.Format {
		case "email":
			m["format"] = "email"
		case "uuid":
			m["format"] = "uuid"
		case "url":
			m["format"] = "uri" // OpenAPI's registered name for URLs
		case "date":
			m["format"] = "date"
		}
		return m
	case "int":
		return oaNumericBounds(map[string]any{"type": "integer", "format": "int32"}, fd)
	case "int64":
		return oaNumericBounds(map[string]any{"type": "integer", "format": "int64"}, fd)
	case "float64":
		return oaNumericBounds(map[string]any{"type": "number", "format": "double"}, fd)
	case "bool":
		return map[string]any{"type": "boolean"}
	case "uuid":
		return map[string]any{"type": "string", "format": "uuid"}
	case "file":
		return map[string]any{"type": "string", "format": "uuid",
			"description": "id of an uploaded file (POST /api/files) attached to this record"}
	case "time":
		return map[string]any{"type": "string", "format": "date-time"}
	case "jsonb":
		// An arbitrary JSON document (a real jsonb column): no fixed shape, and
		// clients send/receive the document itself, not a serialized string.
		return map[string]any{
			"description":    "an arbitrary JSON document (jsonb column)",
			"x-appximo-json": "jsonb",
		}
	case "json":
		// ADR-028: the same document contract as jsonb — clients send and
		// receive the VALUE (object, array, number, boolean; a string is read
		// as JSON text). It used to be published as `"type": "string"`, which
		// made every generic form render a text input (and the value, once
		// native, print as `[object Object]`). The tag tells a generic tool
		// which storage it is (TEXT: not queryable, `eq` over canonical text).
		return map[string]any{
			"description":    "an arbitrary JSON document (json column, stored as canonical JSON text)",
			"x-appximo-json": "text",
		}
	default:
		return map[string]any{"type": "string"}
	}
}

// oaNumericBounds copies the min/max validation rules onto a numeric OpenAPI
// schema as minimum/maximum.
func oaNumericBounds(m map[string]any, fd schema.FieldDef) map[string]any {
	if fd.Min != nil {
		m["minimum"] = *fd.Min
	}
	if fd.Max != nil {
		m["maximum"] = *fd.Max
	}
	return m
}

func oaSortEnum(res *schema.ResourceSchema) []string {
	enum := []string{"id"}
	enum = append(enum, sortedFieldKeys(res)...)
	return enum
}

func oaOpsForType(fieldType string) []string {
	switch fieldType {
	case "string", "text":
		return []string{"eq", "partial"}
	case "int", "int64", "float64":
		return []string{"eq", "gt", "gte", "lt", "lte"}
	case "time":
		return []string{"eq", "after", "before", "gte", "lte"}
	default:
		return []string{"eq"}
	}
}

func oaFilterDesc(field, fieldType string) string {
	ops := oaOpsForType(fieldType)
	return "Filter by " + field + ". Operators: " + strings.Join(ops, ", ")
}

func oaOpDesc(field, op string) string {
	switch op {
	case "partial":
		return "Filter " + field + " using ILIKE (case-insensitive substring match)"
	case "gte":
		return "Filter " + field + " ≥ value"
	case "lte":
		return "Filter " + field + " ≤ value"
	case "gt":
		return "Filter " + field + " > value"
	case "lt":
		return "Filter " + field + " < value"
	case "after":
		return "Filter " + field + " strictly after the given date-time"
	case "before":
		return "Filter " + field + " strictly before the given date-time"
	default:
		return "Filter " + field + " by exact value"
	}
}

// ── helpers ──────────────────────────────────────────────────────────────────

func oaSchemaRef(name string) map[string]any {
	return map[string]any{"$ref": "#/components/schemas/" + name}
}

func oaRespRef(name string) map[string]any {
	return map[string]any{"$ref": "#/components/responses/" + name}
}

func oaJSONContent(s map[string]any) map[string]any {
	return map[string]any{"application/json": map[string]any{"schema": s}}
}

func oaSuccessResp(s map[string]any) map[string]any {
	return map[string]any{"description": "Success", "content": oaJSONContent(s)}
}

func oaErrResp(desc string) map[string]any {
	return map[string]any{"description": desc, "content": oaJSONContent(oaSchemaRef("ErrorResponse"))}
}

func oaQueryParam(name string, s map[string]any) map[string]any {
	return map[string]any{"name": name, "in": "query", "schema": s}
}

func oaQueryParamDesc(name string, s map[string]any, desc string) map[string]any {
	return map[string]any{"name": name, "in": "query", "description": desc, "schema": s}
}

func oaPathIDParam() map[string]any {
	return map[string]any{
		"name":     "id",
		"in":       "path",
		"required": true,
		"schema":   map[string]any{"type": "string", "format": "uuid"},
	}
}

func sortedResourceKeys(s *schema.APISchema) []string {
	keys := make([]string, 0, len(s.Resources))
	for k := range s.Resources {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}

func sortedFieldKeys(res *schema.ResourceSchema) []string {
	keys := make([]string, 0, len(res.Fields))
	for k := range res.Fields {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}
